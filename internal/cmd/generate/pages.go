package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"text/template"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
)

// pagingParams are query parameters that indicate a paginated list.
var pagingParams = map[string]bool{
	"limit": true, "page": true, "cursor": true, "next": true, "nextcursor": true,
}

type pagedOp struct {
	Name       string // Go operation name, e.g. OrdersV4FindPartnerOrders
	Method     string
	Path       string
	ParamDecls string // ", campaignId CampaignIdPath"
	ParamNames string // ", campaignId"
	HasParams  bool
}

// isPaged reports whether op is a GET list operation whose response
// links to the next page.
func isPaged(op codegen.OperationDefinition) bool {
	if op.Method != "GET" || op.Spec == nil || op.Spec.Responses == nil {
		return false
	}
	paged := false
	for _, p := range op.QueryParams {
		if pagingParams[strings.ToLower(p.ParamName)] {
			paged = true
		}
	}
	if !paged {
		return false
	}
	r := op.Spec.Responses.Value("200")
	if r == nil || r.Value == nil {
		return false
	}
	for mt, m := range r.Value.Content {
		if strings.Contains(mt, "json") && m != nil && hasLinks(m.Schema, 0) {
			return true
		}
	}
	return false
}

func hasLinks(s *openapi3.SchemaRef, depth int) bool {
	if s == nil || s.Value == nil || depth > 5 {
		return false
	}
	if _, ok := s.Value.Properties["links"]; ok {
		return true
	}
	if _, ok := s.Value.Properties["_links"]; ok {
		return true
	}
	for _, sub := range s.Value.AllOf {
		if hasLinks(sub, depth+1) {
			return true
		}
	}
	return false
}

func pagedOps(doc *openapi3.T) ([]pagedOp, error) {
	ops, err := codegen.OperationDefinitions(doc)
	if err != nil {
		return nil, err
	}
	var out []pagedOp
	for _, op := range ops {
		if !isPaged(op) {
			continue
		}
		var decls, names strings.Builder
		for _, p := range op.PathParams {
			fmt.Fprintf(&decls, ", %s %s", p.GoVariableName(), p.TypeDef())
			fmt.Fprintf(&names, ", %s", p.GoVariableName())
		}
		out = append(out, pagedOp{
			Name:       op.OperationId,
			Method:     op.Method,
			Path:       op.Path,
			ParamDecls: decls.String(),
			ParamNames: names.String(),
			HasParams:  op.RequiresParamObject(),
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

var pagesTemplate = template.Must(template.New("pages").Parse(`// Code generated by internal/cmd/generate. DO NOT EDIT.

package {{.Package}}

import (
	"context"
	"iter"
	"net/http"
)
{{range .Ops}}
// {{.Name}}Pages iterates over all pages of {{.Method}} {{.Path}}.
// It requests the first page with params and then follows the "next"
// links. Set params.Limit to control the page size.
func (c *ClientWithResponses) {{.Name}}Pages(ctx context.Context{{.ParamDecls}}{{if .HasParams}}, params *{{.Name}}Params{{end}}, reqEditors ...RequestEditorFn) iter.Seq2[*{{.Name}}Response, error] {
	return pages(ctx, c,
		func(ctx context.Context) (*{{.Name}}Response, error) {
			return c.{{.Name}}WithResponse(ctx{{.ParamNames}}{{if .HasParams}}, params{{end}}, reqEditors...)
		},
		Parse{{.Name}}Response,
		func(r *{{.Name}}Response) ([]byte, *http.Response) { return r.Body, r.HTTPResponse },
		reqEditors)
}
{{end}}`))

func generatePages(doc *openapi3.T, pkg string) ([]byte, error) {
	ops, err := pagedOps(doc)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := pagesTemplate.Execute(&buf, map[string]any{"Package": pkg, "Ops": ops}); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format: %w\n%s", err, buf.Bytes())
	}
	return src, nil
}
