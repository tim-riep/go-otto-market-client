package main

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"
	"text/template"

	"github.com/getkin/kin-openapi/openapi3"
)

// acceptRoute is one row of the generated Accept header table.
type acceptRoute struct {
	Method  string
	Pattern string // regular expression for the request path
	Accept  string
	literal int // number of characters outside {params}
}

var pathParam = regexp.MustCompile(`\{[^}/]+\}`)

// acceptHeader builds the Accept value for an operation from the media
// types of its success responses. JSON is always accepted (with lower
// preference if the operation returns something else) because errors are
// returned as JSON.
func acceptHeader(op *openapi3.Operation) string {
	seen := map[string]bool{}
	var types []string
	if op.Responses != nil {
		codes := make([]string, 0, op.Responses.Len())
		for code := range op.Responses.Map() {
			codes = append(codes, code)
		}
		sort.Strings(codes)
		for _, code := range codes {
			r := op.Responses.Value(code)
			if !strings.HasPrefix(code, "2") || r == nil || r.Value == nil {
				continue
			}
			for mt := range r.Value.Content {
				base := strings.ToLower(strings.TrimSpace(strings.SplitN(mt, ";", 2)[0]))
				if !seen[base] {
					seen[base] = true
					types = append(types, base)
				}
			}
		}
	}
	sort.Slice(types, func(i, j int) bool {
		// application/json first, the rest alphabetically.
		if (types[i] == "application/json") != (types[j] == "application/json") {
			return types[i] == "application/json"
		}
		return types[i] < types[j]
	})
	if len(types) == 0 {
		return "application/json"
	}
	if !seen["application/json"] {
		types = append(types, "application/json;q=0.5")
	}
	return strings.Join(types, ", ")
}

func acceptRoutes(doc *openapi3.T) []acceptRoute {
	var routes []acceptRoute
	if doc.Paths == nil {
		return nil
	}
	for path, item := range doc.Paths.Map() {
		for method, op := range item.Operations() {
			// Quote the literal parts, then turn {param} into [^/]+.
			parts := pathParam.Split(path, -1)
			for i := range parts {
				parts[i] = regexp.QuoteMeta(parts[i])
			}
			routes = append(routes, acceptRoute{
				Method:  strings.ToUpper(method),
				Pattern: "^" + strings.Join(parts, "[^/]+") + "$",
				Accept:  acceptHeader(op),
				literal: len(pathParam.ReplaceAllString(path, "")),
			})
		}
	}
	// The most specific path wins: routes with more literal text come
	// first, so "/orders/cancellation" is tried before "/orders/{id}" and
	// "/receipts/{id}.pdf" before "/receipts/{id}".
	sort.Slice(routes, func(i, j int) bool {
		a, b := routes[i], routes[j]
		if a.literal != b.literal {
			return a.literal > b.literal
		}
		if a.Pattern != b.Pattern {
			return a.Pattern < b.Pattern
		}
		return a.Method < b.Method
	})
	return routes
}

var acceptTemplate = template.Must(template.New("accept").Parse(`// Code generated by internal/cmd/generate. DO NOT EDIT.

package {{.Package}}

import "regexp"

// acceptRoutes maps every operation to the Accept header for its
// response media types. The first matching route wins.
var acceptRoutes = []struct {
	method  string
	pattern *regexp.Regexp
	accept  string
}{
{{- range .Routes}}
	{ {{printf "%q" .Method}}, regexp.MustCompile({{printf "%q" .Pattern}}), {{printf "%q" .Accept}} },
{{- end}}
}
`))

func generateAccept(doc *openapi3.T, pkg string) ([]byte, error) {
	var buf bytes.Buffer
	err := acceptTemplate.Execute(&buf, map[string]any{"Package": pkg, "Routes": acceptRoutes(doc)})
	if err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format: %w", err)
	}
	return src, nil
}
